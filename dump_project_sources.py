def find_secret_hits(text: str) -> List[str]:
    hits: List[str] = []
    for name, pat, _repl in _SECRET_PATTERNS:
        try:
            if pat.search(text):
                hits.append(name)
        except re.error:
            # Extremely defensive: if a regex ever fails, don't crash dump.
            continue
    return hits


def redact_secrets(text: str) -> str:
    out = text
    for _name, pat, repl in _SECRET_PATTERNS:
        out = pat.sub(repl, out)
    return out


