def main() -> None:
    default_root = _default_root_dir()

    ap = argparse.ArgumentParser(
        description="Dump project sources into AI-friendly text parts + manifests."
    )
    ap.add_argument(
        "--root",
        type=str,
        default=str(default_root),
        help="Project root to dump. Default: repository root (auto-detected from script location).",
    )
    ap.add_argument(
        "--dump-dir",
        type=str,
        default=DEFAULT_DUMP_DIRNAME,
        help=f"Output folder name under root (default: {DEFAULT_DUMP_DIRNAME}).",
    )
    ap.add_argument(
        "--out-basename",
        type=str,
        default=DEFAULT_OUT_BASENAME,
        help=f"Base name for output dump files (default: {DEFAULT_OUT_BASENAME}).",
    )
    ap.add_argument(
        "--single-file",
        action="store_true",
        help="Write one dump file instead of chunked parts.",
    )
    ap.add_argument(
        "--chunk-mb",
        type=int,
        default=DEFAULT_CHUNK_MB,
        help=f"Max size per part in MB (default: {DEFAULT_CHUNK_MB}). Ignored with --single-file.",
    )
    ap.add_argument(
        "--max-file-mb",
        type=int,
        default=DEFAULT_MAX_FILE_MB,
        help=f"Skip any single file larger than this MB (default: {DEFAULT_MAX_FILE_MB}).",
    )

    # Defaults: normalize EOL ON, line numbers ON (10/10), gitignore ON (10/10)
    ap.add_argument(
        "--no-normalize-eol",
        action="store_true",
        help="Do NOT normalize CRLF/CR to LF.",
    )

    ap.add_argument(
        "--no-line-numbers",
        dest="line_numbers",
        action="store_false",
        help="Disable line numbers.",
    )
    ap.add_argument(
        "--line-numbers",
        dest="line_numbers",
        action="store_true",
        help="Enable line numbers.",
    )
    ap.set_defaults(line_numbers=DEFAULT_LINE_NUMBERS)

    ap.add_argument(
        "--no-respect-gitignore",
        dest="respect_gitignore",
        action="store_false",
        help="Disable gitignore-aware file listing.",
    )
    ap.add_argument(
        "--respect-gitignore",
        dest="respect_gitignore",
        action="store_true",
        help="Enable gitignore-aware file listing.",
    )
    ap.set_defaults(respect_gitignore=DEFAULT_RESPECT_GITIGNORE)

    ap.add_argument(
        "--no-enforce-build-targets",
        dest="enforce_build_targets",
        action="store_false",
        help="Do not force include/report coverage for ace_runtime and ace_tools target roots.",
    )
    ap.add_argument(
        "--enforce-build-targets",
        dest="enforce_build_targets",
        action="store_true",
        help="Force include/report coverage for ace_runtime and ace_tools target roots.",
    )
    ap.set_defaults(enforce_build_targets=True)

    ap.add_argument(
        "--redact-secrets",
        action="store_true",
        help="Redact common secret patterns from content.",
    )
    ap.add_argument(
        "--sanitize-paths",
        action="store_true",
        help="Replace absolute root path occurrences with <ROOT>.",
    )
    ap.add_argument(
        "--omit-timestamps",
        action="store_true",
        help="Omit timestamps in headers/manifests.",
    )
    ap.add_argument(
        "--include-binary-metadata",
        action="store_true",
        help="Include binary/nontext files as metadata-only blocks (content omitted).",
    )

    ap.add_argument(
        "--include-glob",
        action="append",
        default=[],
        help='Only include files matching this glob (repeatable), e.g. "coherence_lang/**".',
    )
    ap.add_argument(
        "--exclude-glob",
        action="append",
        default=[],
        help='Exclude files matching this glob (repeatable), e.g. "**/*.log".',
    )
    ap.add_argument(
        "--exclude-dir",
        action="append",
        default=[],
        help="Exclude directories by name (repeatable).",
    )

    ap.add_argument(
        "--no-git-info",
        action="store_true",
        help="Do not record git metadata in header/manifest.",
    )

    ap.add_argument(
        "--focus",
        type=str,
        default=None,
        help="Focus on a specific folder + its dependencies. E.g. --focus coherence_lang/ui_alpha. "
        "Dumps all files in the focus folder plus any external files they import.",
    )
    ap.add_argument(
        "--focus-depth",
        type=int,
        default=5,
        help="Max depth to trace dependencies from focus folder (default: 5).",
    )
    ap.add_argument(
        "--focus-no-trace",
        action="store_true",
        help="With --focus, only dump the focus folder itself without tracing dependencies.",
    )
    ap.add_argument(
        "--with-tests",
        action="store_true",
        help="With --focus, also include the matching tests folder (e.g., --focus coherence_lang/npe includes tests/npe/**).",
    )
    ap.add_argument(
        "--separate-tests",
        action="store_true",
        help="With --with-tests, output test files to separate dump file(s) (e.g., npe_tests_part01.txt).",
    )

    ap.add_argument(
        "--mode",
        choices=["internal", "share"],
        default="internal",
        help="internal (default) or share (safe: redaction + sanitization + omit timestamps + safe excludes).",
    )

    args = ap.parse_args()

    root = Path(args.root).resolve()
    if not root.exists() or not root.is_dir():
        print(
            f"[error] root does not exist or is not a directory: {root}",
            file=sys.stderr,
        )
        raise SystemExit(2)

    dump_dir = (root / args.dump_dir).resolve()

    exclude_dir_names = set(DEFAULT_EXCLUDE_DIR_NAMES)
    exclude_dir_names.add(args.dump_dir)  # always exclude output dir
    for d in args.exclude_dir:
        exclude_dir_names.add(d)

    include_globs = list(args.include_glob)
    exclude_globs = DEFAULT_EXCLUDE_GLOBS + list(args.exclude_glob)
    test_include_globs: List[str] = []  # Track test globs separately for --separate-tests

    # Handle --focus mode
    focus_external_files: Set[Path] = set()
    if args.focus:
        focus_path: Path = (root / args.focus).resolve()
        if not focus_path.exists() or not focus_path.is_dir():
            print(
                f"[error] focus path does not exist or is not a directory: {focus_path}",
                file=sys.stderr,
            )
            raise SystemExit(2)

        # Add include glob for focus folder
        focus_rel = focus_path.relative_to(root).as_posix()
        include_globs.append(f"{focus_rel}/**")

        print(f"[focus] Targeting: {focus_rel}/")

        # Extract focus folder name for later use
        focus_parts = focus_rel.split("/")
        focus_name = focus_parts[-1]  # e.g., "swarm" from "coherence_lang/npe/swarm"

        # Handle --with-tests: include matching tests folder
        if args.with_tests:

            # Build list of candidate test locations (in priority order)
            test_candidates: List[Tuple[str, str]] = []  # (tests_rel, description)

            # 1. Exact match: coherence_lang/npe/swarm -> tests/npe/swarm/
            if len(focus_parts) >= 2 and focus_parts[0] == "coherence_lang":
                exact_rel = "tests/" + "/".join(focus_parts[1:])
                test_candidates.append((exact_rel, "exact match"))

            # 2. Parent test folder: coherence_lang/npe/swarm -> tests/npe/ (with pattern matching)
            if len(focus_parts) >= 3 and focus_parts[0] == "coherence_lang":
                parent_rel = "tests/" + focus_parts[1]
                test_candidates.append((parent_rel, f"parent folder with *{focus_name}* pattern"))

            # 3. Fallback: tests/<focus_name>/
            test_candidates.append((f"tests/{focus_name}", "fallback"))

            tests_included = False
            for tests_rel, desc in test_candidates:
                tests_path = root / tests_rel
                if tests_path.exists() and tests_path.is_dir():
                    # Check if this is a parent folder case - use pattern matching
                    if "parent folder" in desc:
                        # Find test files matching the focus name pattern
                        pattern = f"*{focus_name}*"
                        matching_files = list(tests_path.glob(f"**/{pattern}.py"))
                        if matching_files:
                            # Add glob for files matching the pattern
                            test_glob = f"{tests_rel}/**/*{focus_name}*.py"
                            test_include_globs.append(test_glob)
                            if not args.separate_tests:
                                include_globs.append(test_glob)
                            print(f"[focus] Including tests: {tests_rel}/**/*{focus_name}*.py ({len(matching_files)} files)")
                            tests_included = True
                            break
                    else:
                        # Exact folder match - include everything
                        test_glob = f"{tests_rel}/**"
                        test_include_globs.append(test_glob)
                        if not args.separate_tests:
                            include_globs.append(test_glob)
                        print(f"[focus] Including tests: {tests_rel}/")
                        tests_included = True
                        break

            if not tests_included:
                print(f"[focus] No matching tests folder found for {focus_rel}")

        if not args.focus_no_trace:
            # Get all files in focus folder first
            print(f"[focus] Scanning for dependencies (depth={args.focus_depth})...")
            focus_files: List[Path] = []
            for dirpath, dirnames, filenames in os.walk(str(focus_path), topdown=True):
                # prune excluded dirs
                pruned = [
                    d
                    for d in list(dirnames)
                    if d in exclude_dir_names or d.endswith(".egg-info")
                ]
                for d in pruned:
                    dirnames.remove(d)
                base = Path(dirpath)
                for name in filenames:
                    focus_files.append(base / name)

            # Trace dependencies
            focus_external_files = trace_dependencies(
                focus_files,
                root,
                max_depth=args.focus_depth,
            )

            # Filter to only files outside focus folder
            focus_external_files = {
                f
                for f in focus_external_files
                if not str(f).startswith(str(focus_path))
            }

            if focus_external_files:
                print(
                    f"[focus] Found {len(focus_external_files)} external dependencies:"
                )
                for ext_f in sorted(
                    focus_external_files,
                    key=lambda p: p.relative_to(root).as_posix().casefold(),
                )[:10]:
                    print(f"        + {ext_f.relative_to(root).as_posix()}")
                if len(focus_external_files) > 10:
                    print(f"        ... and {len(focus_external_files) - 10} more")
            else:
                print(
                    "[focus] No external dependencies found (all imports are within focus folder or external packages)"
                )

    # Auto-generate output basename and subfolder from focus folder if not explicitly set
    out_basename = args.out_basename
    if args.focus and out_basename == DEFAULT_OUT_BASENAME:
        # Use the focus folder name as the basename (e.g., "ui_alpha" -> "ui_alpha_dump")
        out_basename = f"{focus_name}_dump"
        # Put focused dumps in a subfolder: script_dump/<focus_name>/
        dump_dir = dump_dir / focus_name
        print(f"[focus] Output folder: {dump_dir}")
        print(f"[focus] Output basename: {out_basename}")

    normalize_eol_flag = not bool(args.no_normalize_eol)
    line_numbers_flag = bool(args.line_numbers)
    respect_gitignore_flag = bool(args.respect_gitignore)
    enforce_build_targets_flag = bool(args.enforce_build_targets)

    if args.focus and enforce_build_targets_flag:
        print("[focus] disabling build-target enforcement for focus mode")
        enforce_build_targets_flag = False

    # internal defaults
    redact_flag = bool(args.redact_secrets)
    sanitize_flag = bool(args.sanitize_paths)
    omit_ts_flag = bool(args.omit_timestamps)

    # share mode forces safe behavior
    if args.mode == "share":
        redact_flag = True
        sanitize_flag = True
        omit_ts_flag = True
        exclude_globs = exclude_globs + SAFE_SHARE_EXCLUDE_GLOBS

    chunk_size_bytes = int(args.chunk_mb) * 1024 * 1024
    max_file_bytes = int(args.max_file_mb) * 1024 * 1024

    dump_project(
        root=root,
        dump_dir=dump_dir,
        out_basename=out_basename,
        single_file=bool(args.single_file),
        chunk_size_bytes=chunk_size_bytes,
        max_file_bytes=max_file_bytes,
        normalize_eol_flag=normalize_eol_flag,
        line_numbers_flag=line_numbers_flag,
        redact_secrets_flag=redact_flag,
        sanitize_paths_flag=sanitize_flag,
        include_globs=include_globs,
        exclude_globs=exclude_globs,
        exclude_dir_names=exclude_dir_names,
        include_binary_metadata=bool(args.include_binary_metadata),
        respect_gitignore_flag=respect_gitignore_flag,
        enforce_build_targets=enforce_build_targets_flag,
        include_git_info_flag=not bool(args.no_git_info),
        omit_timestamps_flag=omit_ts_flag,
        mode=args.mode,
        focus_external_files=focus_external_files if focus_external_files else None,
    )

    # If --separate-tests is used, create a separate dump for test files
    if args.separate_tests and test_include_globs:
        test_basename = out_basename.replace("_dump", "_tests")
        if test_basename == out_basename:
            test_basename = f"{out_basename}_tests"
        print(f"\n[separate-tests] Creating separate test dump: {test_basename}")
        dump_project(
            root=root,
            dump_dir=dump_dir,
            out_basename=test_basename,
            single_file=bool(args.single_file),
            chunk_size_bytes=chunk_size_bytes,
            max_file_bytes=max_file_bytes,
            normalize_eol_flag=normalize_eol_flag,
            line_numbers_flag=line_numbers_flag,
            redact_secrets_flag=redact_flag,
            sanitize_paths_flag=sanitize_flag,
            include_globs=test_include_globs,
            exclude_globs=exclude_globs,
            exclude_dir_names=exclude_dir_names,
            include_binary_metadata=bool(args.include_binary_metadata),
            respect_gitignore_flag=respect_gitignore_flag,
            enforce_build_targets=False,
            include_git_info_flag=not bool(args.no_git_info),
            omit_timestamps_flag=omit_ts_flag,
            mode=args.mode,
            focus_external_files=None,  # Tests don't need external deps
        )


if __name__ == "__main__":
    main()
