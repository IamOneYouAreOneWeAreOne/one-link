# Patterns to extract imports from various file types
_IMPORT_PATTERNS: Dict[str, List[re.Pattern[str]]] = {
    "python": [
        re.compile(r"^\s*from\s+([\w.]+)\s+import", re.MULTILINE),
        re.compile(r"^\s*import\s+([\w.]+)", re.MULTILINE),
    ],
    "typescript": [
        re.compile(r'import\s+.*?\s+from\s+["\']([^"\']+)["\']', re.MULTILINE),
        re.compile(r'import\s*\(\s*["\']([^"\']+)["\']\s*\)', re.MULTILINE),
        re.compile(r'require\s*\(\s*["\']([^"\']+)["\']\s*\)', re.MULTILINE),
        re.compile(r'export\s+.*?\s+from\s+["\']([^"\']+)["\']', re.MULTILINE),
    ],
    "javascript": [
        re.compile(r'import\s+.*?\s+from\s+["\']([^"\']+)["\']', re.MULTILINE),
        re.compile(r'import\s*\(\s*["\']([^"\']+)["\']\s*\)', re.MULTILINE),
        re.compile(r'require\s*\(\s*["\']([^"\']+)["\']\s*\)', re.MULTILINE),
        re.compile(r'export\s+.*?\s+from\s+["\']([^"\']+)["\']', re.MULTILINE),
    ],
}


def extract_imports(file_path: Path, text: str, lang: str) -> List[str]:
    """Extract import paths from a source file."""
    imports: List[str] = []
    patterns = _IMPORT_PATTERNS.get(lang, [])

    for pat in patterns:
        for match in pat.finditer(text):
            imports.append(match.group(1))

    return imports


def resolve_import_to_file(
    import_path: str,
    source_file: Path,
    root: Path,
    lang: str,
) -> Optional[Path]:
    """Attempt to resolve an import path to an actual file."""
    # Skip node_modules, external packages, etc
    if import_path.startswith(("@", "node_modules", "react", "redux")):
        return None
    if not import_path.startswith((".", "/")):
        # Could be a package - try to resolve as relative to root for Python
        if lang == "python":
            # Convert dots to path separators
            rel_path = import_path.replace(".", "/")
            candidates = [
                root / f"{rel_path}.py",
                root / rel_path / "__init__.py",
            ]
            for cand in candidates:
                if cand.exists():
                    return cand
        return None

    source_dir = source_file.parent

    # Handle relative imports
    if import_path.startswith("./") or import_path.startswith("../"):
        resolved = (source_dir / import_path).resolve()
    elif import_path.startswith("/"):
        # Absolute from root (common in TS/JS with baseUrl)
        resolved = (root / import_path.lstrip("/")).resolve()
    else:
        resolved = (source_dir / import_path).resolve()

    # Try various extensions
    if lang in ("typescript", "javascript"):
        extensions = [
            ".ts",
            ".tsx",
            ".js",
            ".jsx",
            "/index.ts",
            "/index.tsx",
            "/index.js",
        ]
    elif lang == "python":
        extensions = [".py", "/__init__.py"]
    else:
        extensions = [""]

    # If already has extension, check it directly
    if resolved.suffix in (".ts", ".tsx", ".js", ".jsx", ".py"):
        if resolved.exists():
            return resolved

    for ext in extensions:
        candidate = (
            Path(str(resolved) + ext)
            if not ext.startswith("/")
            else resolved / ext.lstrip("/")
        )
        if candidate.exists():
            return candidate

    return None


def trace_dependencies(
    focus_files: List[Path],
    root: Path,
    max_depth: int = 5,
) -> Set[Path]:
    """
    Given a list of focus files, trace their imports and return
    all external files they depend on.
    """
    visited: Set[Path] = set(focus_files)
    external_deps: Set[Path] = set()
    to_process: List[Tuple[Path, int]] = [(f, 0) for f in focus_files]

    while to_process:
        file_path, depth = to_process.pop(0)

        if depth >= max_depth:
            continue

        if not file_path.exists():
            continue

        try:
            text = file_path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue

        lang = detect_lang(file_path)
        imports = extract_imports(file_path, text, lang)

        for imp in imports:
            resolved = resolve_import_to_file(imp, file_path, root, lang)
            if resolved and resolved not in visited:
                visited.add(resolved)
                external_deps.add(resolved)
                # Continue tracing from external deps
                to_process.append((resolved, depth + 1))

    return external_deps


def try_run(cmd: List[str], cwd: Path) -> Optional[str]:
    try:
        proc = subprocess.run(
            cmd,
            cwd=str(cwd),
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return None
    if proc.returncode != 0:
        return None
    return (proc.stdout or "").strip()


def git_info(root: Path) -> Dict[str, object]:
    top = try_run(["git", "rev-parse", "--show-toplevel"], cwd=root)
    if not top:
        return {}
    head = try_run(["git", "rev-parse", "HEAD"], cwd=root) or ""
    branch = try_run(["git", "rev-parse", "--abbrev-ref", "HEAD"], cwd=root) or ""
    describe = (
        try_run(["git", "describe", "--always", "--dirty", "--tags"], cwd=root) or ""
    )
    status = try_run(["git", "status", "--porcelain"], cwd=root)
    return {
        "repo_root": top,
        "head": head,
        "branch": branch,
        "describe": describe,
        "dirty": bool(status),
        "status_porcelain": status.splitlines() if status else [],
    }


def git_ls_files(root: Path) -> Optional[List[str]]:
    top = try_run(["git", "rev-parse", "--show-toplevel"], cwd=root)
    if not top:
        return None
    repo_root = Path(top)

    def run_z(cmd: List[str]) -> Optional[List[str]]:
        try:
            proc = subprocess.run(
                cmd, cwd=str(repo_root), capture_output=True, check=False
            )
        except OSError:
            return None
        if proc.returncode != 0:
            return None
        raw = proc.stdout or b""
        if not raw:
            return []
        parts = raw.split(b"\x00")
        return [p.decode("utf-8", errors="replace") for p in parts if p]

    tracked = run_z(["git", "ls-files", "-z"])
    if tracked is None:
        return None
    others = run_z(["git", "ls-files", "-z", "--others", "--exclude-standard"])
    if others is None:
        return None

    combined = sorted(set(tracked + others), key=lambda s: s.casefold())
    return combined


def enumerate_files(
    root: Path,
    *,
    respect_gitignore: bool,
    exclude_dir_names: Set[str],
) -> List[Path]:
    # Prefer git-aware listing (tracked + untracked not ignored), fallback to os.walk
    if respect_gitignore:
        rels = git_ls_files(root)
        if rels is not None:
            repo_top = try_run(["git", "rev-parse", "--show-toplevel"], cwd=root)
            if repo_top:
                repo_root = Path(repo_top)
                out: List[Path] = []
                for rel in rels:
                    p = repo_root / rel
                    try:
                        p.relative_to(root)
                    except ValueError:
                        continue

                    rel_parts = p.relative_to(root).parts
                    if any(
                        (part in exclude_dir_names) or part.endswith(".egg-info")
                        for part in rel_parts
                    ):
                        continue

                    if p.is_file():
                        out.append(p)

                return sorted(
                    out, key=lambda p: p.relative_to(root).as_posix().casefold()
                )

    # Fallback: os.walk
    files: List[Path] = []
    for dirpath, dirnames, filenames in os.walk(
        str(root), topdown=True, followlinks=False
    ):
        # prune excluded dirs
        pruned = [
            d
            for d in list(dirnames)
            if d in exclude_dir_names or d.endswith(".egg-info")
        ]
        for d in pruned:
            dirnames.remove(d)

        base = Path(dirpath)
        for name in filenames:
            files.append(base / name)

    return sorted(files, key=lambda p: p.relative_to(root).as_posix().casefold())


def write_bytes(out, data: bytes) -> Tuple[int, int]:
    out.write(data)
    return len(data), data.count(b"\n")


