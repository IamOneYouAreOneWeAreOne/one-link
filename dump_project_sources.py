def _norm_rel_root(path: str) -> str:
    return path.replace("\\", "/").strip("/")


def path_matches_target_roots(rel_posix: str) -> bool:
    rel = _norm_rel_root(rel_posix)
    for roots in BUILD_TARGET_ROOTS.values():
        for root in roots:
            rr = _norm_rel_root(root)
            if rel == rr or rel.startswith(rr + "/"):
                return True
    return False


def _expected_target_file_map(all_files_rel: List[str]) -> Dict[str, Set[str]]:
    out: Dict[str, Set[str]] = {}
    for target, roots in BUILD_TARGET_ROOTS.items():
        expected: Set[str] = set()
        for rel in all_files_rel:
            rel_norm = _norm_rel_root(rel)
            for root in roots:
                rr = _norm_rel_root(root)
                if rel_norm == rr or rel_norm.startswith(rr + "/"):
                    expected.add(rel_norm)
                    break
        out[target] = expected
    return out


def compute_build_target_completeness(
    root: Path,
    *,
    all_files_rel: List[str],
    included: List[IncludedFile],
) -> Dict[str, Dict[str, Any]]:
    expected_map = _expected_target_file_map(all_files_rel)
    included_map = {inc.path: inc.sha256 for inc in included}

    report: Dict[str, Dict[str, Any]] = {}
    for target, roots in BUILD_TARGET_ROOTS.items():
        missing_roots = [
            _norm_rel_root(r)
            for r in roots
            if not (root / _norm_rel_root(r)).exists()
        ]
        expected_files = sorted(expected_map.get(target, set()), key=str.casefold)
        missing_files = [p for p in expected_files if p not in included_map]
        included_sha256 = [
            {"path": p, "sha256": included_map[p]}
            for p in expected_files
            if p in included_map
        ]
        report[target] = {
            "target": target,
            "roots": [_norm_rel_root(r) for r in roots],
            "missing_roots": missing_roots,
            "expected_file_count": len(expected_files),
            "included_file_count": len(included_sha256),
            "missing_file_count": len(missing_files) + len(missing_roots),
            "complete": (len(missing_roots) == 0 and len(missing_files) == 0),
            "missing_files": missing_files,
            "included_sha256": included_sha256,
        }
    return report


