import pytest_asyncio  # noqa: E402
from aiohttp.test_utils import TestClient, TestServer  # noqa: E402
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey  # noqa: E402

from one_link.daemon import Daemon  # noqa: E402
from one_link.identity import Identity, fingerprint_of  # noqa: E402
from one_link.server import UIServer  # noqa: E402
from one_link.state import State  # noqa: E402


def _identity(host: str = "cert-host") -> Identity:
    sk = Ed25519PrivateKey.generate()
    pub = sk.public_key()
    pb = pub.public_bytes_raw()
    fp = fingerprint_of(pb)
    return Identity(private=sk, public=pub, public_bytes=pb, fingerprint=fp,
                    short_id=fp[:8], hostname=host)


@pytest_asyncio.fixture
async def live(tmp_path, monkeypatch):
    """A real UIServer with one PINNED peer and one VERIFIED peer in state."""
    monkeypatch.setenv("ONE_LINK_HOME", str(tmp_path))
    state = State(db_path=tmp_path / "state.db")

    pinned_fp, verified_fp = "aa" * 32, "bb" * 32
    for fp, host in ((pinned_fp, "pinned-peer"), (verified_fp, "verified-peer")):
        state.upsert_peer(fingerprint=fp, short_id=fp[:8], pubkey=b"\x01" * 32, hostname=host)
        state.set_peer_trust(fp, "pinned")
    # Only the second one has been verified in person.
    state.set_peer_verified(verified_fp, method="sas-digits", note="test fixture")

    daemon = Daemon(_identity())
    daemon.state = state
    daemon.discovery = None
    daemon._outbound_sessions = {}
    daemon._inbound_regime = {}
    daemon.folder_engine = None

    server = UIServer(daemon)
    client = TestClient(TestServer(server.app))
    await client.start_server()
    try:
        yield client, server, {"pinned": pinned_fp, "verified": verified_fp}
    finally:
        await client.close()
        state.close()


@pytest.mark.asyncio
async def test_the_peers_API_really_returns_a_certified_row(live):
    """THE integration claim, executed rather than grepped.

    If the surface failed to load inside the running server -- a packaging path, a cached
    None, an import ordering problem -- every source assertion above would still pass and
    the product would render nothing proven.
    """
    client, server, _fps = live
    resp = await client.get("/api/peers", headers={"Authorization": f"Bearer {server.token}"})
    assert resp.status == 200, await resp.text()
    peers = (await resp.json()).get("peers") or []
    assert peers, "no peers returned; the assertions below would be vacuous"

    stamped = [p for p in peers if p.get("certified_row")]
    assert stamped, (
        "not one peer carried `certified_row` -- the artifact ships but the running server "
        "does not render from it, which is precisely the gap this work exists to close")
    for p in stamped:
        row = p["certified_row"]
        assert {"glyph", "name_w", "badge_x", "digest"} <= set(row)
        assert row["name_w"] <= row["badge_x"]
        assert row["name_w"] >= 0


@pytest.mark.asyncio
async def test_a_PINNED_but_unverified_peer_does_NOT_get_the_verified_glyph(live):
    """The security property, end to end through the real API.

    Both peers are `trust == "pinned"`. Only one has an in-person SAS verification. If the
    mapping ever collapses those two states, a peer you merely paired with would render as
    verified -- and pairing is a key exchange, not a statement about who is on the far end.
    """
    client, server, _fps = live
    resp = await client.get("/api/peers", headers={"Authorization": f"Bearer {server.token}"})
    peers = (await resp.json()).get("peers") or []
    by_host = {p.get("hostname"): p for p in peers}

    pinned = by_host.get("pinned-peer")
    verified = by_host.get("verified-peer")
    assert pinned and verified, f"fixture peers missing from the API: {sorted(by_host)}"

    assert pinned["trust"] == "pinned" and verified["trust"] == "pinned", (
        "both fixture peers must be pinned, or this test is not isolating VERIFICATION")

    assert pinned["certified_row"]["glyph"] != GLYPH_VERIFIED, (
        "a paired-but-unverified peer renders the VERIFIED glyph")
    assert verified["certified_row"]["glyph"] == GLYPH_VERIFIED, (
        "an in-person-verified peer does NOT render the verified glyph -- the badge would "
        "never appear and the control above would be vacuous")


# ── the UI draws from it, not merely receives it ──────────────────────


def _ui() -> str:
    return (Path(__file__).resolve().parents[1] / "src" / "one_link" / "web" /
            "index.html").read_text(encoding="utf-8")


def test_the_badge_is_decided_by_the_PROVEN_table():
    """The last mile. The server can stamp a proven row and the UI can ignore it.

    `renderConvHeaderTrust` is the function that puts the verified pill on screen. It must
    take its answer from `certified_row.glyph`, not from an ad-hoc `is_verified` conditional
    -- the pixels are the same either way, which is exactly why nothing but a test would
    notice the authority quietly moving back.
    """
    html = _ui()
    assert "function verifiedByProof(peer)" in html, (
        "the UI no longer consults the proven table for the verified badge")
    assert "row.glyph === GLYPH_VERIFIED" in html
    i = html.index("function renderConvHeaderTrust(peer)")
    body = html[i:i + 1400]
    assert "verifiedByProof(peer)" in body, (
        "renderConvHeaderTrust decides the badge without asking the proven renderer")


def test_the_UNPROVEN_fallback_is_never_silent():
    """A fallback nobody can see is how the unproven path comes back.

    When no certified row is present the UI must still render -- but it has to RECORD that
    it fell back, or 'proven' becomes a claim with no way to check it after the fact.
    """
    html = _ui()
    i = html.index("function renderConvHeaderTrust(peer)")
    body = html[i:i + 1400]
    assert 'data-proven' in body, "the fallback does not mark itself"
    assert '"unavailable"' in body


def test_the_verified_glyph_constant_matches_the_server():
    """A constant that drifts between the two sides is a badge that lies on one of them."""
    html = _ui()
    assert "const GLYPH_VERIFIED = 7;" in html
    assert GLYPH_VERIFIED == 7
