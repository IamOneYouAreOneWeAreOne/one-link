"""The peer row is drawn from a proven renderer, and the product actually reaches it.

Three laws are discharged over EVERY integer input by the Coherence prover in the `idem` repo at
build time, and the answers ship as `one_link/certified/peer_row.json`:

    the-verified-glyph-requires-verified-trust    scope: exact
    the-name-never-runs-under-the-badge           scope: exact
    nothing-is-drawn-outside-the-row              scope: exact

WHY THIS FILE EXISTS AND NOT JUST THE PROVER'S TESTS. A proof nothing renders from is a capability,
not a surface. The prover's suite can show the laws hold; only these tests can show that One Link
*loads* the table, *verifies* it, and *stamps it onto the rows the UI receives* — and that it fails
closed when the artifact is wrong instead of quietly drawing unproven rows while the code still
claims a proven one.

The security-critical assertion is `test_the_verified_glyph_NEVER_appears_below_verified_trust`,
swept over the entire shipped state space rather than sampled. It is the product-side statement of
the property the whole thing exists for: a peer cannot make your screen say VERIFIED.
"""

