def test_a_point_outside_the_certified_space_returns_None(surface):
    """Honest emptiness. Extrapolating past the proven domain would be the unproven code
    this replaces, wearing a digest."""
    assert surface.row(VERIFIED, 9999) is None
    assert surface.covers(VERIFIED, 9999) is False
    assert surface.covers(VERIFIED, 0) is True


