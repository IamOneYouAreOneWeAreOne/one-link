def test_the_verified_glyph_NEVER_appears_below_verified_trust(surface, doc):
    """THE property, swept rather than sampled.

    The prover discharged this over every integer. This is the product-side statement:
    every row One Link can actually be asked to draw is checked, so a regression in the
    artifact — a hand-edit, a bad regeneration, a truncated file — is caught here even
    though the theorem upstream is untouched.
    """
    checked = 0
    for row in doc["rows"]:
        trust, name_len = row["in"]["trust"], row["in"]["name_len"]
        got = surface.row(trust, name_len)
        assert got is not None
        if trust != VERIFIED:
            assert got.glyph != GLYPH_VERIFIED, (
                f"trust={trust} name_len={name_len} draws the VERIFIED glyph -- a peer that is "
                "not verified would appear verified on screen")
            assert not got.shows_verified()
        checked += 1
    assert checked == len(doc["rows"]) >= 100, f"only {checked} rows swept"


