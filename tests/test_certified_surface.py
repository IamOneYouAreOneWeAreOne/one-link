def _identity(host: str = "cert-host") -> Identity:
    sk = Ed25519PrivateKey.generate()
    pub = sk.public_key()
    pb = pub.public_bytes_raw()
    fp = fingerprint_of(pb)
    return Identity(private=sk, public=pub, public_bytes=pb, fingerprint=fp,
                    short_id=fp[:8], hostname=host)


@pytest_asyncio.fixture
async def live(tmp_path, monkeypatch):
    """A real UIServer with one PINNED peer and one VERIFIED peer in state."""
    monkeypatch.setenv("ONE_LINK_HOME", str(tmp_path))
    state = State(db_path=tmp_path / "state.db")

    pinned_fp, verified_fp = "aa" * 32, "bb" * 32
    for fp, host in ((pinned_fp, "pinned-peer"), (verified_fp, "verified-peer")):
        state.upsert_peer(fingerprint=fp, short_id=fp[:8], pubkey=b"\x01" * 32, hostname=host)
        state.set_peer_trust(fp, "pinned")
    # Only the second one has been verified in person.
    state.set_peer_verified(verified_fp, method="sas-digits", note="test fixture")

    daemon = Daemon(_identity())
    daemon.state = state
    daemon.discovery = None
    daemon._outbound_sessions = {}
    daemon._inbound_regime = {}
    daemon.folder_engine = None

    server = UIServer(daemon)
    client = TestClient(TestServer(server.app))
    await client.start_server()
    try:
        yield client, server, {"pinned": pinned_fp, "verified": verified_fp}
    finally:
        await client.close()
        state.close()


