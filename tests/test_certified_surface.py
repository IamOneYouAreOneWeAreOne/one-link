# ── the security property, over the WHOLE shipped space ───────────────


def test_the_verified_glyph_NEVER_appears_below_verified_trust(surface, doc):
    """THE property, swept rather than sampled.

    The prover discharged this over every integer. This is the product-side statement:
    every row One Link can actually be asked to draw is checked, so a regression in the
    artifact — a hand-edit, a bad regeneration, a truncated file — is caught here even
    though the theorem upstream is untouched.
    """
    checked = 0
    for row in doc["rows"]:
        trust, name_len = row["in"]["trust"], row["in"]["name_len"]
        got = surface.row(trust, name_len)
        assert got is not None
        if trust != VERIFIED:
            assert got.glyph != GLYPH_VERIFIED, (
                f"trust={trust} name_len={name_len} draws the VERIFIED glyph -- a peer that is "
                "not verified would appear verified on screen")
            assert not got.shows_verified()
        checked += 1
    assert checked == len(doc["rows"]) >= 100, f"only {checked} rows swept"


def test_a_verified_peer_DOES_get_the_glyph(surface):
    """NEGATIVE CONTROL. Every assertion above is satisfied by a renderer that never shows
    the badge at all -- which would be secure, useless, and indistinguishable without this."""
    got = surface.row(VERIFIED, 12)
    assert got is not None and got.shows_verified()


def test_the_name_never_runs_under_the_badge(surface, doc):
    for row in doc["rows"]:
        got = surface.row(row["in"]["trust"], row["in"]["name_len"])
        assert got.name_w <= got.badge_x, (
            f"{row['in']} draws a name {got.name_w}px wide under a badge at {got.badge_x}px")


def test_nothing_is_drawn_at_negative_width(surface, doc):
    """The defect the prover caught before it shipped.

    The first renderer clamped only the HIGH side of the name width. A negative name_len --
    or one large enough that `name_len * 8` wraps in i64 -- produced a NEGATIVE width. No
    test written against plausible names would have found it.
    """
    for row in doc["rows"]:
        got = surface.row(row["in"]["trust"], row["in"]["name_len"])
        assert got.name_w >= 0, f"{row['in']} -> negative width {got.name_w}"


# ── it fails CLOSED ───────────────────────────────────────────────────


def test_an_EDITED_table_is_refused(doc):
    """The forgery: flip a row so an unverified peer shows the verified glyph, keep the digest."""
    forged = copy.deepcopy(doc)
    for row in forged["rows"]:
        if row["in"]["trust"] != VERIFIED:
            row["out"]["glyph"] = GLYPH_VERIFIED
            break
    ok, why = verify(forged)
    assert ok is False, "a table edited after certification was accepted"
    assert "DIGEST MISMATCH" in why


def test_a_TRUNCATED_table_is_refused(doc):
    """A missing point is a broken surface, not a smaller one -- and the digest alone
    cannot catch it, because a truncated table hashes consistently with itself."""
    short = copy.deepcopy(doc)
    short["rows"] = short["rows"][:-1]
    short["table_digest"] = table_digest(short["rows"])      # re-hashed, so only coverage catches it
    ok, why = verify(short)
    assert ok is False
    assert "incomplete table" in why


def test_a_table_with_NO_LAWS_is_refused(doc):
    lawless = copy.deepcopy(doc)
    lawless["laws"] = []
    ok, why = verify(lawless)
    assert ok is False
    assert "lookup table with a hash" in why


