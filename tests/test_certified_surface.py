def test_the_trust_mapping_requires_IN_PERSON_verification():
    """The one judgement call the proof cannot make.

    The law constrains the renderer: glyph 7 only when the level is VERIFIED. WHICH peers
    count as VERIFIED is the product's decision, and it must be `is_verified` (an in-person
    SAS confirmation) rather than `trust == "pinned"`. Pairing means a key exchange
    happened; it does not mean anyone checked who was on the other end.
    """
    src = (Path(__file__).resolve().parents[1] / "src" / "one_link" / "server.py").read_text(
        encoding="utf-8")
    i = src.index("def _certified_row_for")
    body = src[i:i + 1600]
    assert 'p.get("is_verified")' in body and "level = 2" in body, (
        "the VERIFIED level is no longer gated on in-person verification")
    pinned_at = body.index('"pinned"')
    assert "level = 1" in body[pinned_at:pinned_at + 80], (
        "a merely-pinned peer is being mapped to VERIFIED -- pairing is not verification")


# ── it reaches the SHIPPED bundle, not just the checkout ──────────────


def test_the_build_carries_the_artifact_into_the_bundle():
    """The dev-only trap: everything passes in the checkout and the bundle has no table.

    `certified_surface` resolves its artifact beside the package, so if PyInstaller does not
    carry `one_link/certified` the installed app silently loses the proven surface — and
    `available()` returning False looks identical to "not built yet".
    """
    # The artifact lives under `data/`, which the bundle already carries wholesale via
    # `add_data_package`. That is not an accident of convenience: `validate_python_distributions.py`
    # scans exactly `data` and `web` for package data, so a new top-level `certified/` directory
    # was INVISIBLE to the supply-chain contract and produced a wheel that looked valid while
    # omitting the table. Living inside an already-audited subtree is the property under test.
    build = (Path(__file__).resolve().parents[1] / "scripts" / "build_binary.py").read_text(
        encoding="utf-8")
    assert 'package_data_dir = repo / "src" / "one_link" / "data"' in build
    assert "+ add_data_package" in build, (
        "the bundle no longer carries the data subtree, which is where the certified surface "
        "lives -- the installed app would render every row through the unproven fallback")

    from one_link import certified_surface as cs
    assert cs.DEFAULT_ARTIFACT.parts[-3:] == ("data", "certified", "peer_row.json"), (
        f"the artifact moved to {cs.DEFAULT_ARTIFACT} -- outside `data/` it is invisible to both "
        "the wheel's package-data contract and the distribution validator's source scan")
    pyproject = (Path(__file__).resolve().parents[1] / "pyproject.toml").read_text(encoding="utf-8")
    assert '"data/certified/peer_row.json"' in pyproject, (
        "the wheel no longer declares the artifact; a pip install would omit it silently")


def test_the_build_REFUSES_when_the_artifact_is_missing():
    """A skipped-if-absent asset is a dark gate.

    If the build merely omitted a missing artifact, the bundle would run, every row would fall
    back to unproven layout, and the code would still claim a proven surface. That failure is
    invisible from the outside, so the build has to stop.
    """
    build = (Path(__file__).resolve().parents[1] / "scripts" / "build_binary.py").read_text(
        encoding="utf-8")
    i = build.index("certified_dir = repo")
    window = build[i:i + 1200]
    assert "return 6" in window, "a missing certified surface no longer fails the build"
    assert "is_file()" in window


